class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas that writes dynamic total page count on running headers/footers."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        # Top running bar
        self.setFillColor(colors.HexColor('#0F172A'))
        self.rect(36, 802, 523, 2, fill=1, stroke=0)

        self.setFont('Helvetica-Bold', 7)
        self.setFillColor(colors.HexColor('#64748B'))
        self.drawString(36, 808, 'DRIVERXTRA DIGITAL SERVICE PASSPORT')
        self.setFont('Helvetica', 7)
        self.drawRightString(559, 808, 'OFFICIAL VERIFIED VEHICLE RECORD')

        # Bottom footer bar
        self.setFillColor(colors.HexColor('#E2E8F0'))
        self.rect(36, 38, 523, 1, fill=1, stroke=0)

        self.setFont('Helvetica', 7)
        self.drawString(36, 26, 'Generated by DriverXtra Platform Services • Cryptographically Verified')
        self.drawRightString(559, 26, f'Page {self._pageNumber} of {page_count}')
        self.restoreState()


class VehiclePassportPdfService:
    """Generates official, beautifully-formatted PDF Vehicle Service Passports."""

    @classmethod
    def generate_passport_pdf(
        cls,
        vehicle: GarageVehicle,
        records: Sequence[VehicleServiceRecord] | None = None,
    ) -> bytes:
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            leftMargin=36,
            rightMargin=36,
            topMargin=48,
            bottomMargin=48,
        )

        styles = getSampleStyleSheet()
        normal = styles['Normal']

        # Custom paragraph styles
        title_style = ParagraphStyle(
            'PassportTitle',
            parent=normal,
            fontName='Helvetica-Bold',
            fontSize=20,
            leading=24,
            textColor=colors.HexColor('#0F172A'),
        )
        subtitle_style = ParagraphStyle(
            'PassportSubtitle',
            parent=normal,
            fontName='Helvetica',
            fontSize=9,
            leading=13,
            textColor=colors.HexColor('#64748B'),
        )
        section_heading = ParagraphStyle(
            'PassportSection',
            parent=normal,
            fontName='Helvetica-Bold',
            fontSize=11,
            leading=15,
            textColor=colors.HexColor('#0F172A'),
            spaceBefore=8,
            spaceAfter=4,
        )
        card_label = ParagraphStyle(
            'CardLabel',
            parent=normal,
            fontName='Helvetica-Bold',
            fontSize=8,
            leading=10,
            textColor=colors.HexColor('#64748B'),
        )
        card_val = ParagraphStyle(
            'CardValue',
            parent=normal,
            fontName='Helvetica',
            fontSize=9,
            leading=12,
            textColor=colors.HexColor('#0F172A'),
        )
        badge_verified = ParagraphStyle(
            'BadgeVerified',
            parent=normal,
            fontName='Helvetica-Bold',
            fontSize=8,
            leading=10,
            textColor=colors.HexColor('#065F46'),
        )
        badge_buyer = ParagraphStyle(
            'BadgeBuyer',
            parent=normal,
            fontName='Helvetica',
            fontSize=8,
            leading=10,
            textColor=colors.HexColor('#92400E'),
        )
        body_text = ParagraphStyle(
            'BodyTextCustom',
            parent=normal,
            fontName='Helvetica',
            fontSize=8.5,
            leading=11.5,
            textColor=colors.HexColor('#334155'),
        )
        small_muted = ParagraphStyle(
            'SmallMuted',
            parent=normal,
            fontName='Helvetica',
            fontSize=7.5,
            leading=10,
            textColor=colors.HexColor('#64748B'),
        )

        story = []

        # --- 1. HEADER SECTION ---
        header_data = [
            [
                Paragraph('<b>DRIVERXTRA</b> DIGITAL SERVICE PASSPORT', title_style),
                Paragraph(
                    f"<b>Plate:</b> {vehicle.registration_plate or 'UNREGISTERED'}<br/>"
                    f"<b>Generated:</b> {timezone.now().strftime('%d %b %Y, %H:%M UTC')}",
                    subtitle_style,
                ),
            ],
            [
                Paragraph(
                    'Immutable vehicle maintenance provenance, verified workshop records, and parts history.',
                    subtitle_style,
                ),
                Paragraph(
                    f"<b>Passport ID:</b> DX-VP-{str(vehicle.id)[:8].upper()}",
                    subtitle_style,
                ),
            ],
        ]
        header_table = Table(header_data, colWidths=[330, 193])
        header_table.setStyle(
            TableStyle([
                ('VALIGN', (0, 0), (-1, -1), 'TOP'),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 2),
                ('TOPPADDING', (0, 0), (-1, -1), 0),
                ('LEFTPADDING', (0, 0), (-1, -1), 0),
                ('RIGHTPADDING', (0, 0), (-1, -1), 0),
            ])
        )
        story.append(header_table)
        story.append(Spacer(1, 10))

        # --- 2. VEHICLE PROFILE SUMMARY CARD ---
        owner_name = (
            getattr(vehicle.user, 'full_name', '').strip()
            or f"{vehicle.user.first_name} {vehicle.user.last_name}".strip()
            or vehicle.user.email
        )
        odometer_str = f"{vehicle.current_odometer:,} {vehicle.odometer_unit}" if vehicle.current_odometer else 'Not specified'

        specs_data = [
            [
                Paragraph('VEHICLE IDENTIFICATION', card_label),
                Paragraph('TECHNICAL SPECIFICATIONS', card_label),
                Paragraph('REGISTRATION & STATUS', card_label),
            ],
            [
                Paragraph(
                    f"<b>Make & Model:</b> {vehicle.year} {vehicle.make} {vehicle.model}<br/>"
                    f"<b>Trim:</b> {vehicle.trim or 'Standard'}<br/>"
                    f"<b>Reg Plate:</b> {vehicle.registration_plate or 'None'}<br/>"
                    f"<b>VIN:</b> {vehicle.vin or 'Unrecorded'}",
                    card_val,
                ),
                Paragraph(
                    f"<b>Engine Code:</b> {vehicle.engine_code or 'N/A'}<br/>"
                    f"<b>Fuel Type:</b> {vehicle.fuel_type or 'N/A'}<br/>"
                    f"<b>Transmission:</b> {vehicle.transmission or 'N/A'}<br/>"
                    f"<b>Color:</b> {vehicle.color or 'N/A'}",
                    card_val,
                ),
                Paragraph(
                    f"<b>Current Odometer:</b> {odometer_str}<br/>"
                    f"<b>MOT Status:</b> {vehicle.mot_status}<br/>"
                    f"<b>Registered Owner:</b> {owner_name}<br/>"
                    f"<b>Ownership:</b> {vehicle.ownership_status.replace('_', ' ').title()}",
                    card_val,
                ),
            ],
        ]
        specs_table = Table(specs_data, colWidths=[174, 174, 175])
        specs_table.setStyle(
            TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F8FAFC')),
                ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#CBD5E1')),
                ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
                ('TOPPADDING', (0, 0), (-1, -1), 6),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
                ('LEFTPADDING', (0, 0), (-1, -1), 8),
                ('RIGHTPADDING', (0, 0), (-1, -1), 8),
                ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ])
        )
        story.append(specs_table)
        story.append(Spacer(1, 12))

        # --- 3. SERVICE HISTORY STATS BANNER ---
        if records is None:
            records = list(
                VehicleServiceRecord.objects.filter(vehicle=vehicle)
                .select_related('workshop', 'work_order')
                .prefetch_related(
                    'work_order__tasks',
                    'work_order__parts_used',
                    'work_order__quotation',
                )
                .order_by('-service_date', '-created_at')
            )
        else:
            records = list(records)

        verified_count = sum(1 for r in records if r.is_verified)
        buyer_count = len(records) - verified_count

        stats_data = [
            [
                Paragraph(f"<b>Total Service Entries:</b> {len(records)}", card_val),
                Paragraph(f"<b>Platform Verified:</b> {verified_count}", badge_verified),
                Paragraph(f"<b>Self-Reported:</b> {buyer_count}", badge_buyer),
                Paragraph(
                    f"<b>Verification Level:</b> {'FULL PLATFORM VERIFIED' if verified_count and not buyer_count else 'HYBRID RECORD' if verified_count else 'UNVERIFIED'}",
                    card_label,
                ),
            ]
        ]
        stats_table = Table(stats_data, colWidths=[130, 130, 120, 143])
        stats_table.setStyle(
            TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F1F5F9')),
                ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
                ('TOPPADDING', (0, 0), (-1, -1), 4),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
                ('LEFTPADDING', (0, 0), (-1, -1), 8),
                ('RIGHTPADDING', (0, 0), (-1, -1), 8),
                ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ])
        )
        story.append(stats_table)
        story.append(Spacer(1, 10))

        # --- 4. DETAILED SERVICE HISTORY ENTRIES ---
        story.append(Paragraph('VERIFIED SERVICE & MAINTENANCE LEDGER', section_heading))
        story.append(
            Paragraph(
                'Each record represents an authenticated workshop visit or logged maintenance event in chronological sequence.',
                small_muted,
            )
        )
        story.append(Spacer(1, 6))

        if not records:
            empty_table = Table(
                [[Paragraph('No service or maintenance records found for this vehicle.', body_text)]],
                colWidths=[523],
            )
            empty_table.setStyle(
                TableStyle([
                    ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F8FAFC')),
                    ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#E2E8F0')),
                    ('PADDING', (0, 0), (-1, -1), 12),
                    ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
                ])
            )
            story.append(empty_table)
        else:
            for idx, record in enumerate(records, start=1):
                record_flowables = []

                # Badge and Header
                is_platform = record.is_verified and record.record_source == RecordSourceChoices.PLATFORM_VERIFIED
                status_badge = (
                    '<b>[PLATFORM VERIFIED • OFFICIAL WORKSHOP SERVICE]</b>'
                    if is_platform
                    else '<b>[SELF-REPORTED • BUYER ENTERED]</b>'
                )
                badge_style = badge_verified if is_platform else badge_buyer

                date_str = record.service_date.strftime('%d %B %Y') if record.service_date else 'Unknown Date'
                workshop_name = record.service_centre_name or (record.workshop.display_name if record.workshop else 'Private / External Service')

                rec_head_data = [
                    [
                        Paragraph(f"<b>#{idx}. {record.service_title}</b>", card_val),
                        Paragraph(status_badge, badge_style),
                    ],
                    [
                        Paragraph(
                            f"<b>Date:</b> {date_str} &nbsp;|&nbsp; <b>Service Centre:</b> {workshop_name}",
                            small_muted,
                        ),
                        Paragraph(
                            f"<b>Odometer:</b> {f'{record.odometer_reading:,} {record.odometer_unit}' if record.odometer_reading else 'Unrecorded'}"
                            + (f" &nbsp;|&nbsp; <b>Cost:</b> {record.currency} {record.total_cost:,.2f}" if record.total_cost else ''),
                            small_muted,
                        ),
                    ],
                ]

                # If there's an associated work order, include its reference number
                wo = record.work_order
                if wo:
                    lead_name = wo.lead_technician.full_name if wo.lead_technician else 'Assigned Staff'
                    rec_head_data.append([
                        Paragraph(
                            f"<b>Work Order:</b> #{wo.work_order_number} &nbsp;|&nbsp; <b>Status:</b> {wo.status.title()} &nbsp;|&nbsp; <b>Lead Technician:</b> {lead_name}",
                            small_muted,
                        ),
                        Paragraph(
                            f"<b>Quotation Ref:</b> #{wo.quotation.quotation_number if wo.quotation else 'Direct'}",
                            small_muted,
                        ),
                    ])

                rec_head_table = Table(rec_head_data, colWidths=[330, 193])
                rec_head_table.setStyle(
                    TableStyle([
                        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
                        ('TOPPADDING', (0, 0), (-1, -1), 2),
                        ('BOTTOMPADDING', (0, 0), (-1, -1), 2),
                        ('LEFTPADDING', (0, 0), (-1, -1), 0),
                        ('RIGHTPADDING', (0, 0), (-1, -1), 0),
                    ])
                )
                record_flowables.append(rec_head_table)

                # Description / Notes
                if record.description:
                    record_flowables.append(Spacer(1, 4))
                    record_flowables.append(Paragraph(f"<b>Service Summary:</b> {record.description}", body_text))

                # Tasks completed if linked to Work Order
                if wo and hasattr(wo, 'tasks') and wo.tasks.exists():
                    tasks = list(wo.tasks.order_by('order_index'))
                    if tasks:
                        record_flowables.append(Spacer(1, 4))
                        task_rows = [[
                            Paragraph('<b>Completed Tasks / Labour Operations</b>', card_label),
                            Paragraph('<b>Status</b>', card_label),
                            Paragraph('<b>Duration</b>', card_label),
                        ]]
                        for task in tasks:
                            dur_str = f"{task.actual_labour_minutes or task.estimated_labour_minutes or 0} mins"
                            task_rows.append([
                                Paragraph(task.description, small_muted),
                                Paragraph(task.status.replace('_', ' ').title(), small_muted),
                                Paragraph(dur_str, small_muted),
                            ])
                        task_table = Table(task_rows, colWidths=[340, 100, 83])
                        task_table.setStyle(
                            TableStyle([
                                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#F1F5F9')),
                                ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
                                ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#F1F5F9')),
                                ('TOPPADDING', (0, 0), (-1, -1), 2),
                                ('BOTTOMPADDING', (0, 0), (-1, -1), 2),
                                ('LEFTPADDING', (0, 0), (-1, -1), 4),
                                ('RIGHTPADDING', (0, 0), (-1, -1), 4),
                            ])
                        )
                        record_flowables.append(task_table)

                # Parts consumed if linked to Work Order
                if wo and hasattr(wo, 'parts_used') and wo.parts_used.exists():
                    parts = list(wo.parts_used.all())
                    if parts:
                        record_flowables.append(Spacer(1, 4))
                        part_rows = [[
                            Paragraph('<b>Parts Consumed & Installed</b>', card_label),
                            Paragraph('<b>Part Number</b>', card_label),
                            Paragraph('<b>Qty</b>', card_label),
                        ]]
                        for part in parts:
                            part_rows.append([
                                Paragraph(part.part_name, small_muted),
                                Paragraph(part.part_number or 'OEM/Direct', small_muted),
                                Paragraph(str(part.quantity), small_muted),
                            ])
                        part_table = Table(part_rows, colWidths=[340, 120, 63])
                        part_table.setStyle(
                            TableStyle([
                                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#F1F5F9')),
                                ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
                                ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#F1F5F9')),
                                ('TOPPADDING', (0, 0), (-1, -1), 2),
                                ('BOTTOMPADDING', (0, 0), (-1, -1), 2),
                                ('LEFTPADDING', (0, 0), (-1, -1), 4),
                                ('RIGHTPADDING', (0, 0), (-1, -1), 4),
                            ])
                        )
                        record_flowables.append(part_table)

                # Outer card box for this record
                card_data = [[record_flowables]]
                card_table = Table(card_data, colWidths=[523])
                border_color = colors.HexColor('#10B981') if is_platform else colors.HexColor('#CBD5E1')
                card_table.setStyle(
                    TableStyle([
                        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#FFFFFF')),
                        ('BOX', (0, 0), (-1, -1), 1, border_color),
                        ('TOPPADDING', (0, 0), (-1, -1), 6),
                        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
                        ('LEFTPADDING', (0, 0), (-1, -1), 8),
                        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
                    ])
                )
                story.append(KeepTogether(card_table))
                story.append(Spacer(1, 8))

        # --- 5. AUTHENTICITY AND VERIFICATION NOTICE ---
        story.append(Spacer(1, 10))
        legal_text = (
            '<b>Official Statement of Authenticity:</b> This document constitutes a certified digital passport '
            'of vehicle maintenance records maintained within the DriverXtra platform. Platform-verified records '
            'are established upon verified job completion by authenticated partner service centres and backed by '
            'system-audited work orders, technician assignments, and inventory draw downs. Any alteration of this '
            'record invalidates its certified authenticity.'
        )
        legal_table = Table([[Paragraph(legal_text, small_muted)]], colWidths=[523])
        legal_table.setStyle(
            TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F8FAFC')),
                ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
                ('PADDING', (0, 0), (-1, -1), 6),
            ])
        )
        story.append(KeepTogether(legal_table))

        # Build document using NumberedCanvas
        doc.build(story, canvasmaker=NumberedCanvas)
        return buffer.getvalue()

